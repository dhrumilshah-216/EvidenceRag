"""Grounded answer generation module using the official google-genai SDK."""

import os
import re
from typing import Any, Dict, List, Optional, Set

try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    pass

INSUFFICIENT_EVIDENCE_ANSWER = (
    "I do not have sufficient evidence from the provided documents to answer this question."
)


class AnswerGenerator:
    """Generates grounded answers with strict citation validation using Gemini."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model_name: Optional[str] = None,
        client: Optional[Any] = None,
    ):
        """Initializes the AnswerGenerator.

        Args:
            api_key: Optional Gemini API key. If omitted, read from GEMINI_API_KEY env var.
            model_name: Optional Gemini model name. If omitted, read from GEMINI_MODEL env var.
            client: Optional pre-configured client (useful for testing with mocks).

        Raises:
            ValueError: If GEMINI_API_KEY or GEMINI_MODEL is missing or empty.
            RuntimeError: If google-genai client initialization fails.
        """
        # Resolve API key strictly from arguments or environment
        resolved_key = api_key or os.getenv("GEMINI_API_KEY")
        if not resolved_key or not resolved_key.strip():
            raise ValueError(
                "GEMINI_API_KEY is not set. Please set the GEMINI_API_KEY environment variable "
                "or pass it explicitly."
            )

        # Resolve model strictly from arguments or environment - never silently choose a default
        resolved_model = model_name or os.getenv("GEMINI_MODEL")
        if not resolved_model or not resolved_model.strip():
            raise ValueError(
                "GEMINI_MODEL is not set. Please set the GEMINI_MODEL environment variable "
                "or pass it explicitly."
            )

        self.api_key = resolved_key.strip()
        self.model_name = resolved_model.strip()

        if client is not None:
            self.client = client
        else:
            try:
                from google import genai
                self.client = genai.Client(api_key=self.api_key)
            except Exception as exc:
                raise RuntimeError(
                    f"Failed to initialize official google-genai client: {exc}"
                ) from exc

    def build_prompt(self, question: str, passages: List[Dict[str, Any]]) -> str:
        """Constructs a strict grounding prompt using only the supplied evidence passages.

        Args:
            question: User question string.
            passages: List of retrieved chunk dictionaries.

        Returns:
            Formatted prompt string.
        """
        evidence_blocks: List[str] = []
        for passage in passages:
            chunk_id = passage.get("chunk_id", "unknown")
            doc_name = passage.get("document_name", "unknown")
            pages = passage.get("page_numbers", [])
            pages_str = ", ".join(map(str, pages)) if pages else "unknown"
            text = passage.get("text", "").strip()

            evidence_blocks.append(
                f"[Chunk ID: {chunk_id} | Document: {doc_name} | Pages: {pages_str}]\n{text}"
            )

        evidence_section = "\n\n".join(evidence_blocks)

        prompt = (
            "You are an evidence-grounded document question-answering assistant.\n"
            "Answer the user's question using ONLY the provided evidence passages.\n"
            f"If the evidence does not contain sufficient information to answer the question, "
            f"reply strictly with: '{INSUFFICIENT_EVIDENCE_ANSWER}' and provide no citations.\n"
            "Every claim in your answer must be supported by the provided evidence.\n"
            "You MUST cite the source chunk ID in brackets (e.g. [document_chunk_0]) for every factual claim.\n"
            "At the end of your answer, list all cited chunk IDs on a separate line in the format:\n"
            "Citations: <comma-separated chunk IDs>\n\n"
            f"--- EVIDENCE ---\n{evidence_section}\n--- END EVIDENCE ---\n\n"
            f"Question: {question.strip()}\n\n"
            "Answer:"
        )
        return prompt

    def extract_and_validate_citations(
        self,
        response_text: str,
        valid_chunk_ids: Set[str],
    ) -> List[str]:
        """Extracts cited chunk IDs from model output and validates that they exist in evidence.

        Any invented or hallucinated citations not present in valid_chunk_ids are strictly excluded.

        Args:
            response_text: Text generated by the model.
            valid_chunk_ids: Set of valid chunk IDs from the retrieved evidence passages.

        Returns:
            List of verified, non-duplicate cited chunk IDs in encounter order.
        """
        # If response indicates insufficient evidence, return empty citations
        if INSUFFICIENT_EVIDENCE_ANSWER.lower() in response_text.lower():
            return []

        found_citations: List[str] = []

        # 1. Search for explicit 'Citations: ...' section
        citation_line_match = re.search(
            r"(?:citations?|sources?):\s*(.+)", response_text, re.IGNORECASE
        )
        if citation_line_match:
            raw_citations = citation_line_match.group(1)
            # Find candidate chunk ID tokens
            for token in re.findall(r"[\w\.\-]+_chunk_\d+", raw_citations):
                if token in valid_chunk_ids and token not in found_citations:
                    found_citations.append(token)

        # 2. Search for bracketed citations [chunk_id] throughout the answer
        bracketed_matches = re.findall(r"\[([\w\.\-]+_chunk_\d+)\]", response_text)
        for cid in bracketed_matches:
            if cid in valid_chunk_ids and cid not in found_citations:
                found_citations.append(cid)

        # 3. Direct mention of valid chunk IDs in the text
        for cid in valid_chunk_ids:
            if cid in response_text and cid not in found_citations:
                found_citations.append(cid)

        return found_citations

    def generate_answer(
        self,
        question: str,
        passages: Optional[List[Dict[str, Any]]],
    ) -> Dict[str, Any]:
        """Generates an evidence-grounded answer for the given question and passages.

        Args:
            question: The user's natural-language question.
            passages: List of retrieved chunk dictionaries from Phase 4.

        Returns:
            Structured dictionary containing:
            - 'answer' (str): Grounded answer text or insufficient evidence notice.
            - 'cited_chunk_ids' (List[str]): Validated chunk IDs cited in the answer.
            - 'source_references' (List[Dict[str, Any]]): Source metadata for each cited chunk.

        Raises:
            ValueError: If question is empty or not a string.
            RuntimeError: If Gemini API generation fails or returns empty content.
        """
        if not isinstance(question, str) or not question.strip():
            raise ValueError("question must be a non-empty string.")

        # Return explicit insufficient-evidence response when retrieval returns no acceptable evidence
        if not passages or len(passages) == 0:
            return {
                "answer": INSUFFICIENT_EVIDENCE_ANSWER,
                "cited_chunk_ids": [],
                "source_references": [],
            }

        valid_chunk_map: Dict[str, Dict[str, Any]] = {
            p["chunk_id"]: p for p in passages if isinstance(p, dict) and "chunk_id" in p
        }
        valid_chunk_ids: Set[str] = set(valid_chunk_map.keys())

        # Construct prompt
        prompt = self.build_prompt(question=question, passages=passages)

        # Call Gemini via official google-genai SDK
        try:
            response = self.client.models.generate_content(
                model=self.model_name,
                contents=prompt,
            )
        except Exception as exc:
            raise RuntimeError(f"Gemini API generation error: {exc}") from exc

        if not response or not getattr(response, "text", None):
            raise RuntimeError("Gemini API returned an empty response.")

        response_text = response.text.strip()

        # Extract and validate citations (invented citations are strictly eliminated)
        cited_chunk_ids = self.extract_and_validate_citations(
            response_text=response_text,
            valid_chunk_ids=valid_chunk_ids,
        )

        # Build source references for each validated cited chunk
        source_references: List[Dict[str, Any]] = []
        for cid in cited_chunk_ids:
            chunk = valid_chunk_map[cid]
            source_references.append({
                "chunk_id": cid,
                "document_name": chunk.get("document_name", ""),
                "page_numbers": chunk.get("page_numbers", []),
            })

        return {
            "answer": response_text,
            "cited_chunk_ids": cited_chunk_ids,
            "source_references": source_references,
        }

